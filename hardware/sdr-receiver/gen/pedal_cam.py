"""Create a trusted digest list at KiCad export and verify a copied pedal package."""

import argparse
import hashlib
import json
from pathlib import Path
import sys


BOARDS = ('csc-r1p', 'csc-r1p-ctl')
MANIFEST = 'kicad-cam.json'
GERBER_FUNCTIONS = {
    'Copper,L1,Top', 'Copper,L2,Inr', 'Copper,L3,Inr', 'Copper,L4,Bot',
    'SolderPaste,Top', 'SolderPaste,Bot', 'Legend,Top', 'Legend,Bot',
    'SolderMask,Top', 'SolderMask,Bot', 'Profile',
}


def digest(path):
    if not path.is_file() or path.is_symlink() or not path.stat().st_size:
        raise ValueError(f'missing, empty or linked file: {path}')
    return hashlib.sha256(path.read_bytes()).hexdigest()


def payload(package, board):
    gerbers = package / 'gerbers'
    if not gerbers.is_dir() or gerbers.is_symlink():
        raise ValueError('expected a gerbers directory')
    job_name = f'{board}-job.gbrjob'
    digest(gerbers / job_name)
    entries = json.loads((gerbers / job_name).read_text())['FilesAttributes']
    names = {entry['Path'] for entry in entries}
    functions = {entry['FileFunction'] for entry in entries}
    if (
        functions != GERBER_FUNCTIONS
        or len(entries) != len(names)
        or len(entries) != len(GERBER_FUNCTIONS)
        or any(Path(name).name != name or not name.startswith(f'{board}-') for name in names)
    ):
        raise ValueError('Gerber job must list each of the 11 KiCad plots exactly once')

    # KiCad can produce combined drill data or separate plated and non-plated files.
    drill_names = {path.name for path in gerbers.glob('*.drl')}
    valid_drills = ({f'{board}.drl'}, {f'{board}-PTH.drl', f'{board}-NPTH.drl'})
    if drill_names not in valid_drills:
        raise ValueError('expected the KiCad drill set')
    names |= drill_names | {job_name}
    if names != {path.name for path in gerbers.iterdir()}:
        raise ValueError('Gerber directory has missing or unexpected files')

    paths = {f'gerbers/{name}' for name in names}
    paths.update({f'{board}-cpl-top.csv', f'{board}-bom.csv', 'drc-report.txt'})
    return {name: digest(package / name) for name in sorted(paths)}


def write(package, source, board):
    manifest = {
        'version': 1,
        'board': board,
        'source_sha256': {
            f'{board}.{ext}': digest(source / f'{board}.{ext}')
            for ext in ('kicad_pcb', 'kicad_sch', 'kicad_pro')
        },
        'files_sha256': payload(package, board),
    }
    (package / MANIFEST).write_text(json.dumps(manifest, indent=2) + '\n')


def verify(package, manifest_path):
    manifest = json.loads(manifest_path.read_text())
    board = manifest['board']
    if manifest['version'] != 1 or board not in BOARDS:
        raise ValueError('unsupported KiCad CAM manifest')
    expected = manifest['files_sha256']
    if not isinstance(expected, dict):
        raise ValueError('invalid file hashes in the reviewed manifest')
    actual = payload(package, board)
    changed = sorted(p for p in actual.keys() | expected.keys() if actual.get(p) != expected.get(p))
    if changed:
        raise ValueError('files differ from the reviewed KiCad export: ' + ', '.join(changed))
    print(f'{board}: all {len(actual)} fabrication and assembly files match')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(required=True, dest='command')
    create = commands.add_parser('write', help='record hashes of an export just generated by KiCad')
    create.add_argument('package', type=Path)
    create.add_argument('source', type=Path)
    create.add_argument('board', choices=BOARDS)
    check = commands.add_parser('verify', help='compare a package with an independently retained manifest')
    check.add_argument('package', type=Path)
    check.add_argument('manifest', type=Path)
    args = parser.parse_args()
    try:
        if args.command == 'write':
            write(args.package, args.source, args.board)
        else:
            verify(args.package, args.manifest)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        sys.exit(f'Pedal CAM verification failed: {exc}')


if __name__ == '__main__':
    main()
